import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const base=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(base,'../..');
const require=createRequire(path.join(root,'_test_runs/score_workbook/bootstrap.cjs'));
const {Workbook,SpreadsheetFile}=require('@oai/artifact-tool');
const source=JSON.parse(await fs.readFile(path.join(base,'package/review_only/blank_scores.json'),'utf8'));
const wb=Workbook.create();
const sh=wb.worksheets.add('评分表');
const headers=['回答编号','题目ID','评审人','事实准确 0–2','证据支持 0–2','需求完成 0–2','边界处理 0–2','交付判定','严重错误','不可评分原因','依据与备注'];
const fields=['answer_id','case_id','reviewer_id','accuracy_0_2','evidence_0_2','task_fit_0_2','limits_0_2','delivery_judgement','severe_error','unscorable_reason','notes'];
const matrix=[headers,...source.map(r=>fields.map(k=>r[k]===''?null:r[k]))];
sh.getRange('A1:K34').values=matrix;
sh.getRange('A1:M34').format.font={name:'Arial',size:11,color:'#202A35'};
sh.getRange('A1:K1').format={fill:'#2A4057',font:{name:'Arial',size:11,bold:true,color:'#FFFFFF'},wrapText:true,horizontalAlignment:'center',verticalAlignment:'center',rowHeightPx:42};
sh.getRange('A2:K34').format.rowHeightPx=24;
sh.getRange('C2:K34').format.fill='#FFF4D8';
sh.getRange('A1:A34').format.columnWidthPx=90;
sh.getRange('B1:B34').format.columnWidthPx=78;
sh.getRange('C1:C34').format.columnWidthPx=100;
sh.getRange('D1:G34').format.columnWidthPx=108;
sh.getRange('H1:I34').format.columnWidthPx=100;
sh.getRange('J1:J34').format.columnWidthPx=155;
sh.getRange('K1:K34').format.columnWidthPx=230;
sh.getRange('L1:L34').format.columnWidthPx=24;
sh.getRange('M1:M34').format.columnWidthPx=600;
sh.getRange('M1:M5').values=[['填写说明'],['尚未进行新批次真实模型运行。不要为本轮测试替身填写科研质量分。'],['四项每项0–2分。不可评分请留空，并写明原因。'],['先读随包逐题标准，再看真实原回答及实际交付附件。'],['来源：科研复核3a557d4，2026-10-27，第7与10节。']];
sh.getRange('M1').format.font={name:'Arial',size:11,bold:true,color:'#202A35'};
sh.getRange('M1:M5').format.wrapText=false;
sh.dataValidations.add({range:'D2:G34',rule:{type:'whole',operator:'between',formula1:0,formula2:2}});
sh.getRange('H2:H34').dataValidation={rule:{type:'list',values:['完成','部分完成','未交付','不可评分']}};
sh.getRange('I2:I34').dataValidation={rule:{type:'list',values:['是','否','待核对']}};
sh.freezePanes.freezeRows(1);
sh.showGridLines=false;
wb.recalculate();
if(!sh.getRange('D2:G34').values.flat().every(v=>v===null||v===''))throw new Error('Scores are not blank');
const inspect=await wb.inspect({kind:'table',range:'评分表!A1:K6',include:'values,formulas',tableMaxRows:6,tableMaxCols:11,maxChars:2500});
const errors=await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!',options:{useRegex:true,maxResults:20},maxChars:1000});
const out=path.join(base,'outputs/01a15800-7529-7ee0-b82c-8428c7746a68');
await fs.mkdir(out,{recursive:true});
const image=await wb.render({sheetName:'评分表',range:'A1:M34',scale:1,format:'png'});
await fs.writeFile(path.join(out,'blank_scores_preview.png'),new Uint8Array(await image.arrayBuffer()));
const xlsx=await SpreadsheetFile.exportXlsx(wb);
await xlsx.save(path.join(out,'blank_scores.xlsx'));
await fs.copyFile(path.join(out,'blank_scores.xlsx'),path.join(base,'package/review_only/blank_scores.xlsx'));
await fs.writeFile(path.join(base,'blank_scores_checks.json'),JSON.stringify({rows:source.length,score_cells:source.length*4,all_scores_blank:true,all_reviewer_fields_blank:source.every(r=>r.reviewer_id===''),source:'package/review_only/blank_scores.json',artifact_tool_inspect:inspect.ndjson,error_scan:errors.ndjson,rendered:true,native_Excel_acceptance:false},null,2));
console.log('Created 33-row blank review workbook; 132 scores and reviewer fields remain empty.');
